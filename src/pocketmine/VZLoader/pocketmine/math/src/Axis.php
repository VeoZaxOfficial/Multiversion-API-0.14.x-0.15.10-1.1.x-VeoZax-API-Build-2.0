declare(strict_types=1);
namespace pocketmine\math;
final class Axis{
	private function __construct(){
	}
	public const Y = 0;
	public const Z = 1;
	public const X = 2;
	public static function toString(int $axis) : string{
		$result = [
			Axis::Y => "y",
			Axis::Z => "z",
			Axis::X => "x"
		][$axis] ?? null;
		if($result === null){
			throw new \InvalidArgumentException("Invalid axis $axis");
		}
		return $result;
	}}